#!/usr/bin/env python3
"""Encode tile-index FMV keyframes as byte RLE pairs for Moonlight Holler.

Input JSON: {"width":20,"height":18,"frames":[[tile,...], ...]}
Each frame must contain exactly width*height integer tile IDs (0..255).
Output is a C header containing byte RLE streams and per-frame sizes.
"""
import argparse
import json
from pathlib import Path


def encode(values):
    out = []
    i = 0
    while i < len(values):
        value = values[i]
        run = 1
        while i + run < len(values) and values[i + run] == value and run < 255:
            run += 1
        out.extend((run, value))
        i += run
    return out


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--prefix", default="mh_fmv")
    args = parser.parse_args()
    data = json.loads(args.input.read_text(encoding="utf-8"))
    width, height = int(data["width"]), int(data["height"])
    frames = data["frames"]
    if width < 1 or height < 1 or width * height > 65535 or not frames:
        raise SystemExit("invalid dimensions or empty frame list")
    encoded = []
    for number, frame in enumerate(frames):
        if len(frame) != width * height or any(not isinstance(v, int) or v < 0 or v > 255 for v in frame):
            raise SystemExit(f"frame {number} must contain {width*height} byte tile IDs")
        encoded.append(encode(frame))
    lines = ["/* Generated by tools/encode_fmv.py; do not edit by hand. */", "#include <stdint.h>"]
    for i, frame in enumerate(encoded):
        lines.append(f"static const uint8_t {args.prefix}_{i}[] = {{")
        for start in range(0, len(frame), 16):
            lines.append("    " + ", ".join(str(v) for v in frame[start:start+16]) + ",")
        lines.append("};")
    lines.append(f"static const uint8_t * const {args.prefix}_frames[] = {{")
    lines.append("    " + ", ".join(f"{args.prefix}_{i}" for i in range(len(encoded))) + ",")
    lines.append("};")
    lines.append(f"static const uint16_t {args.prefix}_sizes[] = {{")
    lines.append("    " + ", ".join(f"sizeof({args.prefix}_{i})" for i in range(len(encoded))) + ",")
    lines.append("};")
    lines.append(f"#define {args.prefix.upper()}_FRAME_COUNT {len(encoded)}")
    lines.append(f"#define {args.prefix.upper()}_FRAME_TILES {width*height}")
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
